; ============================================================
; BIOS Stage1 引导加载程序（MBR）
; ============================================================
; 这是 BIOS 引导模式下的第一阶段引导代码，必须恰好 512 字节
; 功能：
;   1. 初始化寄存器和堆栈
;   2. 使用 BIOS INT 13h 从磁盘加载 Stage2
;   3. 切换到保护模式（32 位）
;   4. 跳转到 Stage2
;
; 加载地址：BIOS 将 MBR 加载到 0x7c00
; Stage2 加载地址：0x7e00（紧随 MBR 之后）

[bits 16]               ; 实模式（16 位）
[org 0x7c00]            ; MBR 加载到物理地址 0x7c00

; ------------------------------------------------------------
; 入口点
; ------------------------------------------------------------
start:
    ; 清除方向标志（确保字符串操作递增）
    cld

    ; 初始化段寄存器
    ; 为什么设置为 0？
    ;   - BIOS 加载 MBR 后，段寄存器的状态不确定
    ;   - 设置为 0 使得段基址为 0，逻辑地址 = 物理地址
    ;   - 简化地址计算，避免段:偏移的混乱
    xor ax, ax
    mov ds, ax              ; 数据段
    mov es, ax              ; 附加段
    mov ss, ax              ; 堆栈段

    ; 设置堆栈指针
    ; 为什么是 0x7c00？
    ;   - 堆栈向下增长，从 0x7c00 向低地址生长
    ;   - 0x7c00 以下的内存通常是可用的
    ;   - 避免覆盖 MBR 代码（0x7c00-0x7dff）
    mov sp, 0x7c00

    ; 保存 BIOS 传递的启动驱动器号
    ; DL 寄存器包含 BIOS 启动驱动器号（0x80 = 第一块硬盘）
    mov [boot_drive], dl

    ; 打印启动消息
    mov si, msg_loading
    call print_string

; ------------------------------------------------------------
; 加载 Stage2 和内核到内存
; ------------------------------------------------------------
load_stage2:
    ; 使用 BIOS INT 13h, AH=02h 读取磁盘扇区
    ;
    ; 输入：
    ;   AH = 02h（读取扇区功能号）
    ;   AL = 要读取的扇区数
    ;   CH = 柱面号（低 8 位）
    ;   CL = 扇区号（1-63）+ 柱面号（高 2 位）
    ;   DH = 磁头号
    ;   DL = 驱动器号
    ;   ES:BX = 目标内存地址
    ;
    ; 输出：
    ;   CF = 0 成功，CF = 1 失败
    ;   AH = 状态码（0 = 成功）
    ;   AL = 实际读取的扇区数

    mov ah, 0x02            ; 读取扇区功能
    mov al, 128             ; 读取 128 个扇区（64KB）
    mov ch, 0               ; 柱面 0
    mov cl, 2               ; 从扇区 2 开始（扇区 1 是 MBR）
    mov dh, 0               ; 磁头 0
    mov dl, [boot_drive]    ; 启动驱动器
    mov bx, 0x7e00          ; 加载到 0x7e00
    int 0x13                ; 调用 BIOS 磁盘服务
    jc disk_error           ; CF=1 表示错误

    mov ah, 0x02
    mov al, 128             ; 再读 128 个扇区（64KB）
    mov ch, 3
    mov cl, 1
    mov dh, 4
    mov dl, [boot_drive]
    mov bx, 0x9e00
    int 0x13
    jc disk_error

    ; 读取内核到 0x10000（LBA 模式，扩展 INT 13H）
    mov si, disk_address_packet_kernel
    mov ah, 0x42
    mov dl, [boot_drive]
    int 0x13
    jc disk_error

; ------------------------------------------------------------
; 启用 A20 地址线
; ------------------------------------------------------------
; A20 地址线历史背景：
;   - 8086 只有 20 根地址线（1MB 地址空间）
;   - 实模式下，0xFFFF:0xFFFF = 0x10FFEF（超过 1MB）会回绕到 0x0FFEF
;   - 80286 引入 24 根地址线，为了兼容，默认禁用 A20（第 21 根）
;   - 保护模式和长模式需要启用 A20 才能访问完整的地址空间
;
; 为什么需要启用？
;   - 进入保护模式后，没有 A20 则无法访问 1MB 以上的内存
;   - 1MB 以上的内存会回绕到低地址，导致地址混乱
enable_a20:
    mov ax, 0x2401      ; AH=0x24, AL=0x01 表示启用 A20
    int 0x15

; ------------------------------------------------------------
; 加载 GDT 并切换到保护模式
; ------------------------------------------------------------
enter_protected_mode:
    ; 关闭中断（保护模式下需要重新设置 IDT）
    cli

    ; 加载 GDT
    lgdt [gdt_descriptor]

    ; 设置 CR0 的 PE 位（Protection Enable）启用保护模式
    ; 为什么不直接 mov cr0, 1？
    ;   - CR0 的其他位可能有重要设置（如缓存控制）
    ;   - 只修改 PE 位，保留其他位的值
    mov eax, cr0
    or eax, 1               ; 设置位 0（PE 位）
    mov cr0, eax

    ; 长跳转刷新指令流水线并加载新的 CS
    ; 为什么需要长跳转？
    ;   - CPU 流水线中可能有预取的实模式指令
    ;   - 长跳转强制刷新流水线，确保后续指令在保护模式下执行
    ;   - 同时加载新的代码段选择子到 CS
    jmp 0x08:protected_mode ; 0x08 = GDT 中的代码段选择子

; ------------------------------------------------------------
; 辅助函数：打印字符串（SI 指向以 null 结尾的字符串）
; ------------------------------------------------------------
print_string:
    pusha                   ; 保存所有寄存器
.loop:
    lodsb                   ; AL = [DS:SI], SI++
    test al, al             ; 检查是否为 null
    jz .done

    ; 使用 BIOS INT 10h, AH=0Eh 打印字符
    mov ah, 0x0e
    int 0x10
    jmp .loop
.done:
    popa                    ; 恢复所有寄存器
    ret

; ------------------------------------------------------------
; 错误处理
; ------------------------------------------------------------
disk_error:
    mov si, msg_disk_error
    call print_string
    jmp $                   ; 无限循环

; ------------------------------------------------------------
; 32 位保护模式代码
; ------------------------------------------------------------
[bits 32]
protected_mode:
    ; 设置数据段寄存器
    ; 0x10 = GDT 中的数据段选择子
    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax
    mov ss, ax

    ; 设置堆栈指针（保护模式下的堆栈）
    mov esp, 0x90000        ; 使用 640KB 附近的内存作为堆栈

    ; 跳转到 Stage2
    ; Stage2 加载在 0x7e00，现在是保护模式，直接跳转
    jmp 0x7e00

; ------------------------------------------------------------
; GDT（全局描述符表）
; ------------------------------------------------------------
; 为什么需要 GDT？
;   - 保护模式下，段寄存器存储的是段选择子，指向 GDT 中的描述符
;   - 描述符定义了段的基地址、界限、访问权限等
;   - 这里定义最简单的平坦内存模型：代码段和数据段都覆盖整个 4GB 地址空间

gdt_start:
    ; 空描述符（第一个描述符必须为 0）
    dq 0

gdt_code:
    ; 代码段描述符
    ; 基地址 = 0, 界限 = 0xFFFFF (4GB)
    ; 标志：4KB 粒度, 32 位, 可执行, 可读
    dw 0xffff               ; 界限低 16 位
    dw 0                    ; 基地址低 16 位
    db 0                    ; 基地址中 8 位
    db 10011010b            ; 访问字节：P=1, DPL=00, S=1, E=1, DC=0, RW=1, A=0
    db 11001111b            ; 标志 + 界限高 4 位：G=1, D/B=1, L=0, AVL=0, 界限=0xF
    db 0                    ; 基地址高 8 位

gdt_data:
    ; 数据段描述符
    ; 基地址 = 0, 界限 = 0xFFFFF (4GB)
    ; 标志：4KB 粒度, 32 位, 可写
    dw 0xffff               ; 界限低 16 位
    dw 0                    ; 基地址低 16 位
    db 0                    ; 基地址中 8 位
    db 10010010b            ; 访问字节：P=1, DPL=00, S=1, E=0, DC=0, RW=1, A=0
    db 11001111b            ; 标志 + 界限高 4 位
    db 0                    ; 基地址高 8 位

gdt_end:

gdt_descriptor:
    dw gdt_end - gdt_start - 1  ; GDT 大小（界限）
    dd gdt_start                ; GDT 基地址

; ------------------------------------------------------------
; 数据区
; ------------------------------------------------------------
boot_drive:     db 0                        ; 启动驱动器号
msg_loading:    db "Loading AXIS...", 13, 10, 0
msg_disk_error: db "Disk read error!", 13, 10, 0
disk_address_packet_kernel:
    db 0x10                 ; 包大小（16字节）
    db 0                    ; 保留（必须为0）
    dw 0x0020               ; 要读取的扇区数（32个扇区 = 16KB）
    dw 0x0000               ; 目标地址偏移量（16位）
    dw 0x1000               ; 目标地址段（0x1000:0x0000 = 0x10000）
    dq 256                  ; LBA 起始扇区

; ------------------------------------------------------------
; 引导扇区签名
; ------------------------------------------------------------
; 填充到 510 字节，最后两个字节是引导签名 0xAA55
; BIOS 通过检查这个签名来识别有效的引导扇区
times 510-($-$$) db 0
dw 0xaa55               ; 引导扇区签名（小端序）
