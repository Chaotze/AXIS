// ============================================================
// 无锁并发数据结构
// ============================================================
// 基于 CAS 的高并发数据结构，供多核/中断上下文使用。
//
// 为什么"无锁"而非"锁保护"：
// - 中断处理程序中不能睡眠、应避免长时间持锁；
//   无锁结构天然可重入，且竞争时以 CAS 重试代替等待
//
// 为什么节点由调用方提供：
// - 无锁结构的内存回收必须遵循并发安全协议（ABA 防护、
//   延迟回收），"谁回收、何时回收"由调用方掌控最清晰；
//   节点可从静态数组或 slab/kmem_cache 池取出（mm 提供
//   后者），数据结构只维护链接，不拥有节点——这也是
//   Linux llist 等 C 内核无锁结构的标准形态
// - 各结构的 ABA 风险与使用约束见各文件头部说明
//
// 为什么栈/队列节点以别名重导出（StackNode/QueueNode）：
// - 两者各自定义了通用名 Node<T>，同名重导出会产生
//   歧义；别名保留便捷性，子模块路径仍可精确引用

