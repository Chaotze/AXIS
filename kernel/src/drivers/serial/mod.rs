// ============================================================
// 串口设备驱动
// ============================================================
// 提供 16550 兼容串口控制器的内核驱动：调试控制台（COM1）
// 与备用串口（COM2）的初始化、轮询收发。
//
// 为什么串口如此重要：
// - 无显示环境下内核日志的唯一出口（QEMU -serial stdio）
// - panic 信息必须可靠输出到串口
// - 后续网卡/终端等设备也依赖串口链路调试

pub mod uart16550;

// 重新导出常用类型和入口
pub use uart16550::{
    COM1, COM2, Uart16550, COM1_PORT, COM2_PORT,
    init, console_write_byte,
};

/// 串口子系统自测
///
/// 串口没有可读回的环形回源（除非硬件回环），因此自测验证的是
/// 控制器可访问性：向 COM1 输出标记行，并确认 LSR 位可读。
/// 完整收发验证依赖外设（QEMU -serial stdio 可人工观察）。
pub fn selftest() -> bool {
    let ok = COM1.port() == COM1_PORT;
    // 触发一次真实发送（同时作为日志输出，QEMU stdio 可见）
    COM1.write_line("[SERIAL] COM1 16550 self-test");
    ok
}